-- 计费倍率的默认值从 1.0 改成 2.0(DESIGN.md §6.3)。
--
-- 口径的事实:agent 的 tracker 记的是**客户端 ↔ 本机**那一段的 read + write。
-- 而代理要把同样的数据再跟目标站点跑一遍(客户端→本机→目标,目标→本机→客户端),
-- 所以网卡上进出的量约是 tracker 数字的**两倍** —— 而 VPS 厂商按网卡计费。
-- 倍率 1.0 意味着「用户账单只到厂商账单的一半」,默认这样是在替管理员亏钱。
--
-- ── 这张迁移故意什么都不做 ──
--
-- 新用户的 2.0 由 `node_repo::DEFAULT_TRAFFIC_MULTIPLIER` 在 INSERT 时显式写入,
-- 不动 schema 的 `DEFAULT`。两个原因:
--
--   1. **SQLite 改不了列默认值,只能重建整张表。** 而 users 被 002 / 003 各加过
--      一批列(last_reset_ym、tg_* 十来个),重建就得把当前列一个不漏地抄一遍。
--      抄漏一列 = 那一列的数据在人已经在用的库上直接消失,而这段抄写会随着
--      以后每加一列而腐烂,却没有任何东西提醒你回来改它。
--
--   2. **已有用户的倍率必须原样不动。** 那是管理员当时定的价。批量翻倍等于在
--      所有人不知情的情况下把配额砍一半,会让一批人在下一次巡检(30s)里
--      直接被停用 —— 一个「改默认值」的动作不该有这种后果。
--      要改老用户就去用户页按 [E] 改,或者自己写 UPDATE。
--
-- 文件留着是为了让这个决定有个落点:下一个想「改改 DEFAULT 不就行了」的人
-- 会先在这里读到为什么不。迁移器允许纯注释的迁移(split_sql 会丢掉注释块),
-- 版本号照常推进到 6。
